"""Задание 1.2. Печатный текст на фотографии, в том числе в нестандартном положении.

Как запустить, из папки 1.2:

    source .venv/bin/activate
    python recognize.py

В терминал печатаются найденные строки. Картинки и рамки программа не сохраняет.

Интернет после установки не нужен. Веса уже лежат в папке models/.
Библиотека rapidocr при первом запуске скачала их сама и с тех пор
читает только с диска. Свою сеть мы не обучали: это готовые модели PP-OCRv5.

Что происходит с фотографией, три сети подряд:

    1. Детектор находит на снимке области, где есть текст.
       Область — четырёхугольник, поэтому строка может лежать под углом,
       а не строго горизонтально. Это и есть «нестандартное положение».
    2. Классификатор смотрит на каждую найденную строку и решает,
       не стоит ли она вверх ногами (0° или 180°). Если стоит, её переворачивают.
    3. Распознаватель читает уже выровненную строку посимвольно
       и возвращает текст. Язык модели — восточнославянский: русский,
       украинский, белорусский, болгарский, плюс латиница и цифры.
"""

from pathlib import Path

import cv2
import numpy as np
from rapidocr import LangRec, ModelType, OCRVersion, RapidOCR

# Какой файл читать. Меняется только эта строка.
# Путь относительно папки 1.2. Можно подставить свой файл.
IMAGE = "photos/buhanka.jpg"

# Другие фото, которые уже лежат рядом:
# photos/cafe.png
# photos/buhanka.jpg    
# photos/kofeinya.png   
# photos/vermes.png     
# photos/rynok.png      
# photos/note.jpg       

# Папка, в которой лежит этот файл, а не та, откуда его запустили.
# Так путь photos/... находится и если терминал открыт не в 1.2.
ROOT = Path(__file__).resolve().parent

# Сюда rapidocr сохранил три файла .onnx. Это и есть «экспортированная модель».
#   PP-OCRv6_det_small.onnx                  детектор областей с текстом
#   ch_ppocr_mobile_v2.0_cls_mobile.onnx     переворот строки: 0° или 180°
#   eslav_PP-OCRv5_rec_mobile.onnx           чтение символов, кириллица
# onnx — формат, в котором хранятся уже обученные веса. Его исполняет
# onnxruntime, отдельный движок для запуска моделей без обучения.
MODELS = ROOT / "models"


def main() -> None:
    # Относительный путь приклеиваем к папке проекта.
    # Если в IMAGE уже полный путь (/home/...), оставляем его как есть.
    path = Path(IMAGE)
    if not path.is_absolute():
        path = ROOT / path
    if not path.is_file():
        raise SystemExit(f"Файл не найден: {path}")

    # cv2.imread ломается на кириллице в пути («Документы»).
    # Поэтому файл читаем как набор байтов, а картинку собираем уже из них.
    # IMREAD_COLOR даёт обычное цветное изображение в порядке каналов BGR.
    data = np.fromfile(path, dtype=np.uint8)
    image = cv2.imdecode(data, cv2.IMREAD_COLOR)
    if image is None:
        raise SystemExit(f"Не удалось открыть изображение: {path}")

    # RapidOCR склеивает детектор, классификатор поворота и распознаватель.
    # Параметры ниже говорят библиотеке, какую именно сохранённую модель взять.
    engine = RapidOCR(
        params={
            # Не качать заново и не искать веса в системной папке:
            # брать файлы из нашей models/.
            "Global.model_root_dir": str(MODELS),
            # Иначе библиотека пишет в терминал служебный журнал и мешает тексту.
            "Global.log_level": "error",
            # Язык распознавателя. ESLAV — восточнославянская группа, нужен русский.
            # Детектор при этом общий: он ищет пятна текста, а не буквы конкретного языка.
            "Rec.lang_type": LangRec.ESLAV,
            # MOBILE — компактная версия сети. На процессоре она быстрее большой SERVER.
            "Rec.model_type": ModelType.MOBILE,
            # Поколение модели. Пятая версия PP-OCR, у неё есть отдельная кириллица.
            "Rec.ocr_version": OCRVersion.PPOCRV5,
        }
    )

    # Один вызов делает всю цепочку: найти строки, при необходимости
    # перевернуть каждую, прочитать символы.
    result = engine(image)

    # txts — кортеж строк в порядке, в котором их вернула библиотека
    # (обычно сверху вниз). Если текста нет, там None, поэтому подставляем ().
    lines = result.txts or ()
    print("\n".join(lines) if lines else "Текст не найден.")


# Этот блок выполняется только когда файл запустили напрямую:
# python recognize.py
# Если кто-то сделает import recognize, распознавание само не стартует.
if __name__ == "__main__":
    main()
